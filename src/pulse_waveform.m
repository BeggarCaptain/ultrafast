function [w, t] = pulse_waveform(P)
%PULSE_WAVEFORM  发射脉冲（单程）的时域波形：高斯包络正弦。
%
%   [W, T] = PULSE_WAVEFORM(P) 返回列向量 W 与时间轴 T [s]，采样率 P.sampleRate。
%
%   它在整条链路里的位置
%   --------------------
%   这是全项目唯一的脉冲定义：f2_setup 把它交给 xdc_impulse（于是它就是阵元
%   辐射的声压波形），图 F2 直接画它，pulse_stats 在它上面量中心频率与带宽。
%   三处共用同一份代码，改载频或改 sigma 时不会出现"图与仿真不是同一个脉冲"。
%
%   原理：时域波形与频谱是一对傅里叶变换
%   ------------------------------------
%   高斯包络 exp(-t^2/(2 sigma^2)) 的幅度谱仍是高斯 exp(-2 pi^2 sigma^2 f^2)，
%   与载波相乘只是把这条谱搬到 +-f_c 处。所以"包络多宽"直接就是"带宽多宽"：
%   幅度降到一半（−6 dB）的两个频率相距
%       带宽_6dB = 0.375 / sigma
%   sigma 用载波周期作单位时（sigma_cyc = 0.32），相对带宽约 0.375/0.32 = 117 %。
%   实测（本函数、30 MHz 采样、5 个周期窗）：-6 dB 112 %、半功率 78 %——图 F2 右图
%   标题里的两个百分数就是它们。解析式偏宽两个来源：记录只留 5 个周期，以及调制使
%   ±f_c 两个高斯像相互重叠——把窗长加到 20 个周期也只回到 114.6 %，所以 117 % 只能
%   当量级估计。**改带宽的唯一旋钮就是 sigma**，不必再调别的。
%
%   为什么选高斯包络
%   ----------------
%   ① 它是时宽-带宽积的下界函数（不确定性原理取等号的那一支），同样时长的脉冲
%      里它的频谱最窄、最干净，没有旁瓣和 sinc 振铃；矩形包络会在谱上留下
%      旁瓣，量带宽时容易被旁瓣误导。
%   ② 解析可算：带宽与 sigma 一一对应（上式），"按论文给参数"时可以反推 sigma，
%      不必试凑。
%
%   为什么只管单程
%   --------------
%   发射只走一趟，所以这里给的是单程波形。成像用的是两程回波，其频谱是单程谱
%   的平方再乘阵元孔径的空间响应：中心会从 4.50 MHz 下移到约 4.12 MHz、−6 dB
%   带宽从 112 % 收窄到 86 %。这个下移来自"裸阵元没有电-机带通整形"这一建模
%   选择（把想要的波形直接当冲激响应），E0 已记录在案，不靠抬高载频去补偿。
%
%   窗长与两个工程约定
%   ------------------
%   窗长 = 3 + ceil(6*sigma_cyc) 个载波周期，右侧 6 sigma 处包络约 1e-8，再长
%   也看不出差别——所以它是**派生量、不可辨识**：5/6/8 个周期给出同一条脉冲
%   的数字。早先它曾是独立参数 P.pulseHalfLen，会和 sigma 脱钩（改了 sigma 忘了
%   改它就把脉冲截断），已删除。峰位固定在第 3 个载波周期：沿袭早期写法，实际
%   只要头部余量 >= 5 sigma 就够，取 3 是为了与旧结果可比。
%
%   一个容易误算的地方
%   ------------------
%   波形峰值 max|W| 约 0.72，不是 1：包络峰值处载波恰好过零，相邻的载波峰被包络
%   衰减到 exp(-(1/(4 sigma_cyc))^2/2) = 0.74。要换算绝对声压时不能拿 1 去乘。

fc  = P.pulseCarrierFreq;                        % 载频 [Hz]
sig = P.pulseSigmaCycles / fc;                   % 高斯 sigma [s]
nCyc = 3 + ceil(6*P.pulseSigmaCycles);           % 窗长 [载波周期数]

t = (0:round(nCyc/fc*P.sampleRate))' / P.sampleRate;          % 时间轴 [s]
w = exp(-((t - 3/fc).^2) / (2*sig^2)) .* sin(2*pi*fc*(t - 3/fc));
end
