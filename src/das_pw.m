function [img, w2] = das_pw(rf, t0, alpha, P, x, z, dt)
%DAS_PW  单次平面波发射的延时叠加（DAS）波束形成：把 128 通道合成一幅图。
%
%   [IMG, W2] = DAS_PW(RF, T0, ALPHA, P, X, Z, DT)
%
%   它在整条链路里的位置
%   --------------------
%   acquire_pw 给出 128 个阵元各自的接收波形（还没有"成像"）；本函数把它们变成
%   一幅 [深度 x 横向] 的射频图；stage_analysis 再把 11 个角度的图在射频域相加
%   （相干复合）、取包络、转 dB。所以"计算成像"真正发生在这里。
%
%   原理：为什么相加就能成像
%   ------------------------
%   一次发射后 128 个阵元收到的是同一个声场，但同一个散射点的回波到达各阵元的
%   路程不同，波形彼此错开。对某个像素 (x,z)，按它到各阵元的几何路程把通道信号
%   各自"退回去" tau(x,z,x1)，再相加：该像素的回波被对齐、同相叠加（幅度约 128
%   倍），其它位置的回波对齐错了、相位散开、互相抵消。这就是合成孔径——用 128
%   个通道的相干求和换一个接收焦点，而且这个焦点是**逐像素**独立形成的，不是
%   "聚焦一次、只清楚一个深度"。
%
%   延时模型的四项分别是什么
%   ------------------------
%     tau = (z*cos(alpha) + x*sin(alpha))/c   ① 发射：倾斜波前到达 (x,z)
%         + sqrt(z^2 + (x-x1)^2)/c            ② 接收：回波从 (x,z) 回到阵元 x1
%         + x1*sin(alpha)/c                   ③ Field II 时间轴修正（报告 6.1）
%         + dt                                ④ 全局时间零点（E0 标定）
%   ①②是物理路程（单程发射 + 单程接收，往返各算一次，所以不除 2）；③不是物理
%   量，而是 Field II 的内部约定——它把发射延时写进了每条通道的时间轴，不补回来
%   图像会横向剪切（E0 实测：带此项残差 0.01 µs，不带 1.2 µs）；④吸收换能器与
%   电子学的固定延迟，每次发射一个值。
%
%   为什么用线性插值，而不是取最近的采样点
%   --------------------------------------
%   tau 换算成采样下标几乎总是小数，必须插值。采样间隔 1/fs = 33 ns 对应往返
%   路程 c/fs = 51 µm；若直接取最近点，延时就被量化成 51 µm 的台阶，相当于把
%   0.19 mm 的轴向分辨率切掉四分之一，相位误差还会在求和时漏能。对相邻两点做
%   线性插值，误差降到二阶；E0 实测残差 −22.6 dB（相对主瓣，约 7 % 幅度）。
%
%   接收孔径为什么取 |x1 - x| <= z/(2F)
%   -----------------------------------
%   接收端固定 F 数：半孔径随深度线性张开。太窄则横向分辨率差（孔径越小、焦斑
%   越宽），太宽则近场相位误差大、还把视场外的噪声收进来。F = 1.75 与论文一致。
%   窗口外权重为 0，且不再乘变迹——论文也不用变迹；矩形窗在散斑上只是旁瓣略高，
%   不影响分辨率与对比度的比较。
%
%   输出
%     img   ：[numel(z) x numel(x)] 动态接收聚焦后的实数射频。包络与对数压缩
%             由调用者稍后完成，这样多个角度可以在射频域相加（相干复合）。先取
%             包络再加是"非相干复合"，相位丢了，拿不到 11 角度复合的增益。
%     w2    ：[numel(z) x numel(x)] 插值权重的平方和。DAS 对每个像素都是一次
%             线性加权求和；若输入噪声是方差 σ_e² 的独立同分布样本，输出噪声
%             方差就是 σ_e²·w2。有了它，噪声图与 SNR 可解析算出（stage_sigma
%             用蒙特卡洛验证过），不必为每个角度再真跑一遍噪声。

if nargin < 7 || isempty(dt), dt = 0; end

z = z(:);  x = x(:).';                  % 强制：深度为列，横向为行
[Nt, Nch] = size(rf);
Nz = numel(z);  Nx = numel(x);
img = zeros(Nz, Nx);
w2  = zeros(Nz, Nx);

ca = cos(alpha);  sa = sin(alpha);
off = (0:Nch-1) * Nt;                   % 各通道在线性索引中的偏移
dxe = P.elementX;                       % 1 x N 阵元坐标

for k = 1:Nx                            % 一次算一条线（内存受限）
    xc = x(k);
    axc = abs(dxe - xc);                % 阵元到像素的横向距离，1 x N
    hw  = z / (2*P.fNumber);            % 各深度的半孔径宽度，Nz x 1
    m   = axc <= hw;                    % Nz x N 孔径掩膜（隐式扩展）

    % Field II 返回的每个通道都把自己的发射延时加在了时间轴上（E0 实测：
    % 带此项残差 0.01 µs，不带则 1.2 µs）。所以延时必须包含这一项。
    tau = (z*ca + xc*sa)/P.soundSpeed + sqrt(z.^2 + (dxe - xc).^2)/P.soundSpeed ...
          + dxe*sa/P.soundSpeed + dt;
    pos = (tau - t0) * P.sampleRate + 1;   % 1 基的（小数）采样下标

    i0 = floor(pos);                    % 左侧相邻采样
    fr = pos - i0;                      % 插值权重，[0,1)
    % 记录窗只有记录长度这么多：延时落到窗外（太浅或太深）的像素根本没有回波
    % 数据，权重置 0，该像素留空而不是被边缘数据冒充。
    m  = m & (i0 >= 1) & (i0 < Nt);     % 延时超出记录范围的像素置零

    % 先钳位再取值：MATLAB 里越界索引会直接报错，而被掩掉的像素权重已是 0，
    % 钳位后的数值不会进入结果。顺序不能反——先钳位再判越界就永远判不出来了。
    i0 = min(max(i0, 1), Nt-1);         % 钳位，保证取值下标永远合法
    v0 = rf(i0 + off);                  % 左侧采样值
    v1 = rf(i0 + 1 + off);              % 右侧采样值

    w0 = (1 - fr) .* m;                 % 线性插值权重（已乘掩膜）
    w1 = fr .* m;

    img(:, k) = sum(w0.*v0 + w1.*v1, 2);% 沿阵元方向相干求和
    w2(:, k)  = sum(w0.^2 + w1.^2, 2);  % 同一求和的噪声功率增益
end
end
