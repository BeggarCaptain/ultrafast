function w = crossing_width(v, p, lvl)
%CROSSING_WIDTH  一维曲线在指定电平处的宽度（交叉点线性插值）。
%
%   W = CROSSING_WIDTH(V, P, LVL) 返回曲线 P 在峰值两侧穿过 LVL*max(P) 的两点
%   之间的距离。交叉点先在采样网格上定位，再在相邻两个采样点之间做线性插值
%   细化，因此结果不会被像素尺寸量化（这一点很关键：轴向 PSF 只有约 0.19 mm
%   宽，而网格是 0.05 mm）。
%
%   为什么阈值取"相对峰值"而不是绝对值
%   ----------------------------------
%   lvl 乘上峰值，结果就与图像的整体增益、显示动态范围、有没有噪声都无关。这样
%   无噪图与含噪图、单平面波与复合、不同深度之间才可以直接比——否则一次增益变化
%   就能把"宽度"改掉。
%
%   为什么只在交叉点附近做线性插值，而不拟合模型
%   --------------------------------------------
%   点扩散函数的包络并不严格是高斯的（旁瓣、孔径边缘、复合都会改变形状），套一个
%   解析模型会把模型误差算进宽度。交叉点两侧的两个采样点已经把真实曲线夹住，
%   在它们之间线性插值是一阶无偏的，也不需要假设形状。
%
%   输入
%     v   ：坐标向量（mm 或 m，返回值单位与之一致）
%     p   ：曲线（包络或强度），长度与 V 相同
%     lvl ：相对峰值的线性阈值，例如 0.5 求 -6 dB（半幅度）宽度；本项目的
%           横向与轴向点扩散函数宽度都用它。
%
%   输出
%     w   ：该电平处的全宽；若某一侧始终没降到阈值以下（例如平顶曲线），返回 NaN。
%           宁可变 NaN 也不返回一个被边界截断的假宽度——调用者必须看见"量不出来"。

v = v(:);
p = p(:);

[~, ip] = max(p);                       % 峰值位置
thr = lvl * p(ip);                      % 换算成绝对阈值
n = numel(p);

% ---- 从峰值向左走，直到曲线降到阈值以下 --------------------------------
iL = ip;
while iL > 1 && p(iL) > thr
    iL = iL - 1;
end
if iL == ip                            % 峰值本身已在阈值以下
    w = NaN; return;
end
vL = interp1([p(iL); p(iL+1)], [v(iL); v(iL+1)], thr, 'linear', 'extrap');

% ---- 从峰值向右走，同理 ------------------------------------------------
iR = ip;
while iR < n && p(iR) > thr
    iR = iR + 1;
end
if iR == ip                            % 右半边没有穿过阈值
    w = NaN; return;
end
vR = interp1([p(iR-1); p(iR)], [v(iR-1); v(iR)], thr, 'linear', 'extrap');

w = vR - vL;                           % 该电平处的全宽
end
