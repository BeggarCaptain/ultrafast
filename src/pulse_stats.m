function s = pulse_stats(rf, fs)
%PULSE_STATS  测量两程脉冲的中心频率、-6 dB 带宽与半功率带宽。
%
%   S = PULSE_STATS(RF, FS) 从“单散射子”采集的数据测量脉冲回波小波的频谱：
%   取最强通道、加窗、补零、做 FFT，然后在幅度谱上定位 -6 dB 与半功率两个电平
%   的边沿。
%
%   输入
%     rf ：[Nt x Nch] 单个点散射子的通道数据
%     fs ：采样率 [Hz]
%
%   输出结构体
%     f1, f2    ：下/上 -6 dB 频率 [Hz]（幅度比 0.501）
%     fc        ：中心频率，(f1+f2)/2，即 -6 dB 两交点的中点 [Hz]
%     bw        ：相对 -6 dB 带宽，(f2-f1)/fc
%     f1hp,f2hp ：下/上 半功率（-3 dB）频率 [Hz]（幅度比 0.708）
%     bwHp      ：相对半功率带宽，(f2hp-f1hp)/(f1hp+f2hp)*2
%     f, S      ：频率轴 [Hz] 与频谱 [dB]，供图 F2 使用
%     wav       ：实际参与分析的加窗波形
%     ich       ：所用的通道号
%
%   为什么两个电平都报
%   ------------------
%   20*log10(幅度) 与 10*log10(功率) 是同一个数轴（因为 20log10 A = 10log10 A^2），
%   所以电平与阈值之间只有一组对应关系：
%     -6 dB  <=> 幅度 0.501  <=> 功率 0.25（四分之一功率）
%     -3 dB  <=> 幅度 0.708  <=> 功率 0.50（半功率）
%   本项目的分辨率指标（横向、轴向都取半幅度 0.5）和 to_db 都在幅度 dB 上，
%   所以主口径取 -6 dB；半功率值一并给出，因为“60 % 设计目标”当初是按它调的。
%
%   为什么取最强通道：点散射子在阵列轴线上，各通道看到的脉冲基本相同，取最强
%   的那个只是为了让测量信噪比最高。记录很短（约 300 个采样点），所以用 Tukey
%   窗抑制截断旁瓣，并用 8 倍补零把交叉点插值出来。
%
%   补零不增加信息，只是把频谱的采样点变密：交叉点原本落在两个频点之间，补零后
%   可以直接取到 0.1 % 的频率精度，不必再做一次人工插值。Tukey(0.1) 只压两端
%   各 5 % 的记录，主瓣几乎不受影响——窗太重会把带宽读窄。
%
%   只保留 0..fs/2 这一半：实信号的 FFT 是对称的，如果整轴搜索，会先碰到
%   fs - f 处的镜像，报出一个荒唐的带宽（这个坑真的踩过一次）。

[~, ich] = max(max(abs(rf), [], 1));        % 最强通道
w    = rf(:, ich) .* tukeywin(size(rf, 1), 0.1);   % 端点加窗，抑制截断旁瓣
nfft = 8 * numel(w);                        % 8 倍补零，得到更细的频率网格
S    = abs(fft(w, nfft));
f    = (0:nfft-1)' * fs / nfft;

half = f < fs/2;                            % 只保留物理上有意义的一半
f = f(half);  S = S(half);
S = S / max(S);                             % 归一化到 0 dB（峰值处 S = 1）

% ---- -6 dB 边沿：幅度 0.501（主口径） ---------------------------------
idx = find(S >= 10^(-6/20));                % 0.5012
s.f1 = f(idx(1));                           % 下边沿
s.f2 = f(idx(end));                         % 上边沿
s.fc = (s.f1 + s.f2) / 2;                   % 中心频率（-6 dB 中点，标准定义）
s.bw = (s.f2 - s.f1) / s.fc;                % 相对 -6 dB 带宽

% ---- 半功率边沿：幅度 0.708（-3 dB，供“60 % 设计目标”对照） ----------
% 每个电平的相对带宽都用它自己的中点作分母，这是分数带宽的标准写法；
% 两个中点的差别只有 0.5 %，但各用各的才能保持两个数字都与历史记录一致。
ihp = find(S >= 10^(-3/20));                % 0.7079
s.f1hp = f(ihp(1));
s.f2hp = f(ihp(end));
fchp   = (s.f1hp + s.f2hp) / 2;
s.bwHp = (s.f2hp - s.f1hp) / fchp;

s.f  = f;
s.S  = 20*log10(max(S, 1e-12));             % dB 频谱，加下限以便画图
s.wav = w;
s.ich = ich;
end
