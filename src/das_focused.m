function [img, w2] = das_focused(rf, t0, xf, P, z, dt)
%DAS_FOCUSED  单条聚焦 B 模式线的延时叠加波束形成。
%
%   [IMG, W2] = DAS_FOCUSED(RF, T0, XF, P, Z, DT)
%
%   它在整条链路里的位置
%   --------------------
%   acquire_focused 发射一次、返回 128 通道；本函数只重建**这一条线**上的像素，
%   输出是列向量。128 条线拼起来才是整幅 B 模式图（stage_analysis 负责拼）。
%   与 das_pw 的区别：一次平面波发射能重建整幅图，而一次聚焦发射只照亮一条线，
%   所以这里没有"横向"这个维度可算。
%
%   延时模型（设计文档式 7）
%   ------------------------
%     tau = [z + (|F| - zf)]/c                  发射：先走到焦点，再沿轴走 z-zf
%         + sqrt(z^2 + (xf-x1)^2)/c            接收：回波从 (xf,z) 回到阵元 x1
%         + (|F| - |F-x1|)/c                   Field II 时间轴修正（报告 6.1）
%         + dt                                 全局时间零点（E0）
%
%   发射项为什么必须是 |F| + (z - zf)，而不能只写 z
%   ----------------------------------------------
%   聚焦发射时各阵元按 d(x1) = (|F| - |F-x1|)/c 先后发出，声波**收敛**到焦点
%   F = (xf, 0, zf)，在 t = |F|/c 同时到达；越过焦点之后才沿轴向发散。所以从
%   阵列中心算起的发射路程是 |F| + (z - zf)，不是像素深度 z。
%
%   只看轴上（xf=0）时两者恰好相等（|F| = zf），这个差别不会暴露；一旦 |xf| > 0，
%   |F| = sqrt(xf^2 + zf^2) > zf，模型就短算了 |F| - zf。镜像的深度是往返标度
%   （tau 里发射、接收各出现一次 z），所以短算的时间折成深度要减半：
%
%       delta(xf) = ( sqrt(xf^2 + zf^2) - zf ) / 2
%
%   xf = 12 mm 时 delta = 1.16 mm，阵列边缘（21 mm）时 3.3 mm。实测（单散射子，
%   修复前）：z = 30 mm 的点在 xf = 0/3/6/9/12 mm 的线上分别偏 +0.005/+0.055/
%   +0.300/+0.655/+1.160 mm，与上式逐点吻合（残差 <= 0.025 mm），且与目标深度
%   无关（整条线整体下移）。它曾表现为图 F13 里 ±12 mm 两个点深了 1.18 mm，
%   并把囊肿体模 ±12 mm 列的 ROI 推离囊心、使聚焦对比度被低估约 6 dB
%   （16.0 -> 21.8 dB）。归档见 docs/实验报告_讨论与附录.md 的 B20。
%
%   为什么是加常数项、而不是把 z 换成逐阵元的 |P-x1|
%   ------------------------------------------------
%   缺的是一个**每线常数** |F| - zf，不是阵元间差异：实测把 sqrt((xf-x1)^2+z^2)
%   代进去几乎不改变结果（31.16 -> 31.13 mm）。补上常数项后 ±12 mm 的点回到
%   30.00 mm，轴上 6 个点不变。
%
%   横向宽度不受这一项影响：它只是把整条线在深度上平移，焦点处 0.64 mm（与
%   lambda*F = 0.65 mm 一致）、焦外 0.79–0.90 mm 都仍然成立。
%
%   输出
%     img ：[numel(z) x 1] 该条线的波束形成结果（实数射频，未取包络）
%     w2  ：[numel(z) x 1] 插值权重平方和（噪声增益，含义同 das_pw）

if nargin < 6 || isempty(dt), dt = 0; end

z = z(:);                       % 强制深度为列向量
[Nt, Nch] = size(rf);
dxe = abs(P.elementX - xf);           % 1 x N，阵元到该线的距离
hw  = z / (2*P.fNumber);           % Nz x 1，动态接收半孔径
m   = dxe <= hw;                % Nz x N 接收孔径掩膜
off = (0:Nch-1) * Nt;           % 各通道线性索引偏移

% 发射路程：阵列中心 -> 焦点（|F|），再沿轴向走到深度 z（z-zf 可正可负）。
% 写成 z 时，|xf| > 0 的整条线会偏深 (|F|-zf)/2，见文件头与附录 B20。
Fd = sqrt(xf^2 + P.txFocusDepth^2);      % |F|，阵列中心到焦点的距离
tx = z + (Fd - P.txFocusDepth);          % 发射路程 [m]

tau = (tx + sqrt(z.^2 + dxe.^2))/P.soundSpeed + dt ...
      + (Fd - sqrt((xf - P.elementX).^2 + P.txFocusDepth^2))/P.soundSpeed;
pos = (tau - t0) * P.sampleRate + 1;    % 小数采样下标
i0  = floor(pos);
fr  = pos - i0;
m   = m & (i0 >= 1) & (i0 < Nt);

i0 = min(max(i0, 1), Nt-1);     % 钳位，保证取值合法
v0 = rf(i0 + off);
v1 = rf(i0 + 1 + off);
w0 = (1 - fr) .* m;             % 线性插值权重（乘孔径掩膜）
w1 = fr .* m;

img = sum(w0.*v0 + w1.*v1, 2);  % 沿接收孔径相干求和
w2  = sum(w0.^2 + w1.^2, 2);    % 噪声功率增益
end
